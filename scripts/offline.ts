// Offline play (a Vite plugin): after a production build, writes sw.js, a
// service worker that keeps every file of the build on the device. The
// game then opens without a connection (everything but online play, the
// shop and accounts works offline). Each build gets its own cache name, so
// a new version replaces the old files as soon as it's been fetched.
// The phone apps don't need it (their files are already on the phone).

import type { Plugin } from 'vite';
import { createHash } from 'node:crypto';

/** The service worker itself, given the files to keep and this build's id. */
export function serviceWorker(files: string[], version: string): string {
  return `// Generated by scripts/offline.ts: keeps the game on the device for offline play.
const CACHE = 'tardigeddon-${version}';
const FILES = ${JSON.stringify(['./', ...files])};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  // Older versions' files go.
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('tardigeddon-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  // Only our own files: never the game server, accounts or payments.
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  if (req.mode === 'navigate') {
    // The page: fresh when online (so updates arrive), the kept copy when not.
    e.respondWith(fetch(req).catch(() => caches.match('./', { ignoreSearch: true, ignoreVary: true })));
    return;
  }
  // Built files never change (their names carry a hash): the kept copy first.
  // (ignoreVary: module scripts send an Origin header the kept copies were fetched without.)
  e.respondWith(caches.match(req, { ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`;
}

export function offline(): Plugin {
  let mode = 'production';
  return {
    name: 'tardigeddon-offline',
    apply: 'build',
    configResolved(config) {
      mode = config.mode;
    },
    generateBundle(_options, bundle) {
      // Not in the phone apps' build (vite build --mode app): their files are on the phone already.
      if (mode === 'app') return;
      // Every built file (but source maps, and the older .woff fonts every browser that has
      // service workers can do without), plus the icon and manifest from public/.
      const files = [...Object.keys(bundle).filter((f) => !f.endsWith('.map') && !f.endsWith('.woff')), 'icon.svg', 'manifest.webmanifest'].sort();
      const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(files, version) });
    },
  };
}
