const ALPHA2 = new Map(
  PAIRS.trim()
    .split(/\s+/)
    .map((p) => [p.slice(0, 3), p.slice(3)] as const),
);

/** "JPN" → "JP"; null for anything unknown. */
export function countryFromStorefront(storefront: unknown): string | null {
  return typeof storefront === 'string' ? (ALPHA2.get(storefront.toUpperCase()) ?? null) : null;
}
